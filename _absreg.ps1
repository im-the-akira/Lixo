$ErrorActionPreference='Continue'
$root='Kairo Tweaker/modules'
$out='78.ArquivosDoAcervo.ps1'
$lines=@()
$lines+='# ====================================================================='
$lines+= '# Kairo Tweaker :: 78.ArquivosDoAcervo.ps1'
$lines+= '# ABORDAGEM: cada .reg/.bat/.cmd/.ps1 do acervo vira opções GRANULARES'
$lines+= '# (1 ação = 1 opção, com Explicação e Problema). Os .reg sao aplicados'
$lines+= '# com reg import; os .bat/.cmd com Start-Process; os .ps1 com dot sourcing.'
$lines+= '# ====================================================================='
$lines+=''
$lines+= 'Write-Host ("" " + ("=" * 72)) -ForegroundColor Cyan'
$lines+= 'Write-Host "  ABORDAGEM DOS ARQUIVOS DO ACERVO - KAI RO OPTIMIZER v2.0.0" -ForegroundColor Magenta'
$lines+= 'Write-Host (" " + ("=" * 72)) -ForegroundColor Cyan'
$lines+= ''
$lines+= 'function Add-FileTweak {'
$lines+= 'param('
$lines+= ' [string]$Id,'
$lines+= ' [string]$Categoria,'
$lines+= ' [string]$Risco,'
$lines+= ' [string]$Nome,'
$lines+= ' [string]$Explicacao,'
$lines+= ' [string]$Problema,'
$lines+= ' [string]$Comando,'
$lines+= ' [string]$Reverso'
$lines+= ' )'
$lines+= ' $global:KT_Registry.Add(@{'
$lines+= ' Id=$Id; Categoria=$Categoria; Risco=$Risco; Reinicio=$true;'
$lines+= ' Nome=$Nome; Explicacao=$Explicacao; Problema=$Problema'
$lines+= ' }) > $null'
$lines+= ' $global:KT_Comandos[$Id] = @($Comando, $Reverso)'
$lines+= '}'
$lines+= ''
$lines+= 'Write-Host "  Lendo 3 - Regedits ... " -ForegroundColor Yellow'
$lines+= 'Get-ChildItem "3 - Regedits" -Recurse -Filter *.reg -File -ErrorAction SilentlyContinue | Sort-Object DirectoryName, Name | ForEach-Object {'
$lines+= ' $f = $_.FullName; $id = "reg.3." + (Get-Item $f).Name.Replace(" ","").Replace(".reg","").Replace("Undo_","undo-")'
$lines+= ' $nome = (Get-Item $f).Name.Replace(".reg","")'
$lines+= ' $explic = "Origem: 3 - Regedits\/"+ (Split-Path $f -Leaf).Replace(".reg","").Replace("Undo_","")'
$lines+= ' $problema = "Abrir o arquivo .reg no Regedit e confirmar cada valor (System.Restart aufhören, Inaktivität etc.). Nenhum dano."
'
$lines+= ' Add-FileTweak -Id $id -Categoria "Otimização do Windows" -Risco "Baixo" -Nome ("Reg edit: " + $nome) -Explicacao $explic -Problema $problema -Comando ('reg import "' + $f + '"') -Reverso ("echo Reverter: abrir em Regedit e reverter os valores do arquivo original")
$lines+= '}'
$lines+= ''
$lines+= 'Write-Host "  Lendo 8 - Ativadores e scripts ... " -ForegroundColor Yellow'
$lines+= 'Get-ChildItem "8 - Ativadores" -Recurse -Filter *.cmd -File -ErrorAction SilentlyContinue | Sort-Object DirectoryName, Name | ForEach-Object {'
$lines+= ' $f = $_.FullName; $id = "cmd.8." + (Get-Item $f).Name.Replace(" ","").Replace(".cmd","")'
$lines+= ' $nome = (Get-Item $f).Name.Replace(".cmd","")'
$lines+= ' $explic = "Origem: 8 - Ativadores\/"+ (Split-Path $f -Leaf).Replace(".cmd","")'
$lines+= ' $problema = "Clica velozmente no arquivo pelo CMD (desnecessário se já aplicado)."
'
$lines+= ' Add-FileTweak -Id $id -Categoria "Otimização do Windows" -Risco "Baixo" -Nome ("CMD: " + $nome) -Explicacao $explic -Problema $problema -Comando ('cmd "/c ""' + $f + '"') -Reverso ('echo Reverter: abrir O arquivo .cmd de novo e confirmar')
$lines+= '}'
$lines+= ''
$lines+= 'Write-Host "  Lendo MinProcessos.ps1 ... " -ForegroundColor Yellow'
$lines+= 'Add-FileTweak -Id "ps.minprocessos" -Categoria "MinTestros" -Risco "Baixo" -Nome ("Script: MinProcessos") -Explicacao "Origem: MinProcessos.ps1 - diminui o numero de processos abertos e libera memoria." -Problema "O uso de muitos processos pode causar lentidao no Windows." -Comando ('powershell -NoProfile -ExecutionPolicy Bypass -File "C:\ProgramData\MinProcessos.ps1"') -Reverso ('echo Reverter via MasterOptimizer')
$lines+= ''
$lines+= 'Write-Host "  Lendo Desabilitar-servicos.ps1 ... " -ForegroundColor Yellow'
$lines+= 'Add-FileTweak -Id "ps.desatserv" -Categoria "Serviços" -Risco "Baixo" -Nome ("Script: Desabilitar Serviços") -Explicacao "Origem: desabilitar-servicos.ps1 - desativa serviços indesejados." -Problema "A desativação de serviços pode causar instabilidade no Windows." -Comando ('powershell -NoProfile -ExecutionPolicy Bypass -File "C:\ProgramData\desabilitar-servicos.ps1"') -Reverso ('echo Reverter via MasterOptimizer')
$lines+= ''
$lines+= 'Write-Host "  Lendo RemoverAI-UpdateCleanup.ps1 ... " -ForegroundColor Yellow'
$lines+= 'Add-FileTweak -Id "ps.cleanup" -Categoria "Limpeza" -Risco "Baixo" -Nome ("Script: Remove AI Update Cleanup") -Explicacao "Origem: RemoveAI-UpdateCleanup.ps1 - remove atualizações indesejadas." -Problema "A remoção de atualizações pode causar problemas de segurança." -Comando ('powershell -NoProfile -ExecutionPolicy Bypass -File "C:\ProgramData\RemoveAI-UpdateCleanup.ps1"') -Reverso ('echo Reverter via MasterOptimizer')
$lines+= ''
$lines+= 'Write-Host "  Gerando... " -ForegroundColor Green'
$lines+= 'Write-Host "  Arquivo gerado: " + $out -ForegroundColor Green'
$lines+= '# EOF'
$lines+= ''
$lines -join "`n" | Out-File -FilePath $out -Encoding UTF8
Write-Host "OK: $out criado" -ForegroundColor Green
